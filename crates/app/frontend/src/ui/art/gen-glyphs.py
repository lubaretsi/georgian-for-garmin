# Writes glyphs.ts: the outlines of the few words the illustrations draw, taken from the
# bundled Noto Sans Georgian (its Georgian and Latin subsets), so the drawings hold no text
# nodes and look the same on every platform.
#
# Run from crates/app/frontend after changing a word or upgrading the font:
#   uv run --with fonttools --with brotli python src/ui/art/gen-glyphs.py
import json
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

FILES = Path("node_modules/@fontsource-variable/noto-sans-georgian/files")
OUT = Path(__file__).with_name("glyphs.ts")

# name: (text, weight): the answer samples (§5.2), the idle face's time, the install picture's
# greeting ("hello!") and the app icon's letter.
WORDS = {
    "georgian": ("ქართ", 600),
    "questionMarks": ("????", 600),
    "someLetters": ("ქა", 600),
    "greeting": ("სალამი!", 600),
    "time": ("10:09", 500),
    "appLetter": ("ქ", 700),
}

_fonts = {}


def font(subset, weight):
    if (subset, weight) not in _fonts:
        variable = TTFont(FILES / f"noto-sans-georgian-{subset}-wght-normal.woff2")
        _fonts[subset, weight] = instantiateVariableFont(variable, {"wght": weight})
    return _fonts[subset, weight]


def outline(text, weight):
    paths, x = [], 0
    for ch in text:
        georgian = 0x10A0 <= ord(ch) <= 0x10FF or 0x1C90 <= ord(ch) <= 0x1CBF
        f = font("georgian" if georgian else "latin", weight)
        assert f["head"].unitsPerEm == 1000
        glyphs = f.getGlyphSet()
        glyph = glyphs[f.getBestCmap()[ord(ch)]]
        pen = SVGPathPen(glyphs, ntos=lambda v: str(round(v)))
        # Fonts draw y up; SVG is y down. Each glyph moves by the advances before it.
        glyph.draw(TransformPen(pen, (1, 0, 0, -1, x, 0)))
        paths.append(pen.getCommands())
        x += glyph.width
    return {"width": x, "d": " ".join(p for p in paths if p)}


lines = [
    "// Generated by gen-glyphs.py from the bundled Noto Sans Georgian (OFL): the outlines of the",
    "// few words the illustrations draw, so the drawings hold no text nodes (contrast checks can't",
    "// measure text inside SVG) and look the same on every platform. Units: 1000 per em, y down,",
    "// baseline at 0, starting at x 0. Don't edit by hand; rerun the script.",
    "",
    "export type Word = { d: string; width: number };",
    "",
    "export const WORDS = {",
]
for name, (text, weight) in WORDS.items():
    word = outline(text, weight)
    lines.append(f"  {name}: {{ width: {word['width']}, d: {json.dumps(word['d'])} }},")
lines += ["} as const satisfies Record<string, Word>;", ""]
OUT.write_text("\n".join(lines))
