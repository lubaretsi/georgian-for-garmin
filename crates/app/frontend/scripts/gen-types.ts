// Writes src/core/types.gen.ts from the JSON Schemas the Rust code declares: the operations'
// (`georgian-for-garmin --help --json`) and the app's own types for its commands (`Failure`,
// `Progress`, `Shared`, …: `georgian-for-garmin-app --schemas`, debug builds only). Run in
// `nix develop`: `pnpm gen:types`. CI runs it and fails on any diff.
//
// The CLI is `$GEORGIAN_FOR_GARMIN_CLI` and the app `$GEORGIAN_FOR_GARMIN_APP` if set, else
// each is built from this checkout with cargo. Every schema and its `$defs` go into one file: a
// definition that two schemas share must be identical, and is written once.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { compile, type JSONSchema } from "json-schema-to-typescript";

type Schema = { title?: string; $defs?: Record<string, Schema>; [key: string]: unknown };
type Tool = { name: string; inputSchema: Schema; outputSchema: Schema };

const frontend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repo = path.resolve(frontend, "../../..");
const out = path.join(frontend, "src/core/types.gen.ts");

/** The JSON that `--help --json` or `--schemas` of `pkg` prints; `override` is a built binary. */
function run(override: string | undefined, pkg: string, flags: string[]): unknown {
  const [command, args] = override
    ? [override, flags]
    : ["cargo", ["run", "--quiet", "--locked", "-p", pkg, "--", ...flags]];
  const stdout = execFileSync(command, args, { cwd: repo, encoding: "utf8", maxBuffer: 64 << 20 });
  return JSON.parse(stdout);
}

function help(): { tools: Tool[] } {
  return run(process.env.GEORGIAN_FOR_GARMIN_CLI, "georgian-for-garmin", ["--help", "--json"]) as {
    tools: Tool[];
  };
}

function appSchemas(): Record<string, Schema> {
  return run(process.env.GEORGIAN_FOR_GARMIN_APP, "georgian-for-garmin-app", ["--schemas"]) as Record<
    string,
    Schema
  >;
}

/**
 * `#/$defs/X` → `#/definitions/X`, everywhere in a schema. A `$ref` loses its sibling keys
 * (schemars adds the property's `description` and `default`): json-schema-to-typescript would
 * otherwise declare a numbered copy of the referenced type for each such property.
 */
function rewriteRefs(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(rewriteRefs);
  if (value && typeof value === "object") {
    if ("$ref" in value && typeof value.$ref === "string") {
      return { $ref: value.$ref.replace(/^#\/\$defs\//, "#/definitions/") };
    }
    return Object.fromEntries(Object.entries(value).map(([key, inner]) => [key, rewriteRefs(inner)]));
  }
  return value;
}

const definitions: Record<string, Schema> = {};
function define(name: string, schema: Schema, from: string): void {
  const existing = definitions[name];
  if (existing && JSON.stringify(existing) !== JSON.stringify(schema)) {
    throw new Error(`${from}: "${name}" differs from an earlier schema's definition of it`);
  }
  definitions[name] = schema;
}

const operations: Record<string, Schema> = {};
for (const tool of help().tools) {
  const refs: Record<string, Schema> = {};
  for (const side of ["inputSchema", "outputSchema"] as const) {
    const { $defs = {}, $schema: _schema, ...top } = tool[side];
    const title = top.title;
    if (!title) throw new Error(`${tool.name}: its ${side} has no title`);
    for (const [name, def] of Object.entries($defs)) define(name, def, tool.name);
    define(title, top, tool.name);
    refs[side === "inputSchema" ? "input" : "output"] = { $ref: `#/definitions/${title}` };
  }
  operations[tool.name] = {
    type: "object",
    additionalProperties: false,
    properties: refs,
    required: ["input", "output"],
  };
}

// The app's own types, written beside the operations' (unreachable from `Operations`).
for (const [name, schema] of Object.entries(appSchemas())) {
  const { $defs = {}, $schema: _schema, ...top } = schema;
  if (top.title !== name) throw new Error(`the app's ${name} schema is titled ${top.title}`);
  for (const [inner, def] of Object.entries($defs)) define(inner, def, `the app's ${name}`);
  define(name, top, "the app");
}

const root = rewriteRefs({
  title: "Operations",
  description: "Each operation's input and output, by the operation's name.",
  type: "object",
  additionalProperties: false,
  properties: operations,
  required: Object.keys(operations),
  definitions: Object.fromEntries(Object.entries(definitions).sort(([a], [b]) => a.localeCompare(b))),
}) as JSONSchema;

const ts = await compile(root, "Operations", {
  bannerComment:
    "/* Generated by scripts/gen-types.ts from `georgian-for-garmin --help --json` and `georgian-for-garmin-app --schemas`. Don't edit: run `pnpm gen:types`. */",
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
});
writeFileSync(out, ts);
console.log(`wrote ${path.relative(frontend, out)}`);
